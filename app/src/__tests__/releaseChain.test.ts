function fixture(eol = '\n'): Record<string, string> {
  const conv = (s: string) => s.replace(/\n/g, eol);
  return {
    'app/package.json': conv(PKG),
    'app/package-lock.json': conv(LOCK),
    'app/src-tauri/tauri.conf.json': conv(CONF),
    'app/src-tauri/Cargo.toml': conv(TOML),
    'app/src-tauri/Cargo.lock': conv(CARGO_LOCK),
  };
}

function changedLines(a: Record<string, string>, b: Record<string, string>): string[] {
  const out: string[] = [];
  for (const f of Object.keys(a)) {
    const la = a[f].split('\n');
    const lb = b[f].split('\n');
    expect(lb.length).toBe(la.length);
    la.forEach((l, i) => {
      if (l !== lb[i]) out.push(`${f}:${i + 1}:${lb[i].replace(/\r$/, '')}`);
    });
  }
  return out;
}

const SITES = [
  'package.json',
  'package-lock.json#version',
  'package-lock.json#packages[""]',
  'tauri.conf.json',
  'Cargo.toml',
  'Cargo.lock#labnoteo-app',
];

describe('VERSION_FILES', () => {
  it('names the five files that hold the six sites, repo-relative', () => {
    expect([...VERSION_FILES].sort()).toEqual(Object.keys(fixture()).sort());
  });
});

describe('bumpPatch', () => {
  it('bumps the patch number', () => {
    expect(bumpPatch('0.1.0')).toBe('0.1.1');
    expect(bumpPatch('0.1.9')).toBe('0.1.10');
    expect(bumpPatch('1.20.99')).toBe('1.20.100');
  });
  it('throws on anything but x.y.z', () => {
    for (const bad of ['', '0.1', '0.1.0-beta', 'v0.1.0', '0.1.0.1', ' 0.1.0', '01.a.0', '01.1.0']) {
      expect(() => bumpPatch(bad)).toThrow();
    }
  });
});

describe('readVersions', () => {
  it('reads all six sites', () => {
    const v = readVersions(fixture());
    expect(Object.keys(v).sort()).toEqual([...SITES].sort());
    for (const s of SITES) expect(v[s]).toBe('0.1.0');
  });
  it('reads CRLF files too', () => {
    const v = readVersions(fixture('\r\n'));
    for (const s of SITES) expect(v[s]).toBe('0.1.0');
  });
  it('throws when a file is missing', () => {
    const f = fixture();
    delete f['app/src-tauri/Cargo.lock'];
    expect(() => readVersions(f)).toThrow(/Cargo\.lock/);
  });
});

describe('setVersion', () => {
  it('changes exactly the six sites and nothing else', () => {
    const before = fixture();
    const after = setVersion(before, '0.1.1');
    expect(changedLines(before, after)).toEqual([
      'app/package.json:4:  "version": "0.1.1",',
      'app/package-lock.json:3:  "version": "0.1.1",',
      'app/package-lock.json:9:      "version": "0.1.1",',
      'app/src-tauri/tauri.conf.json:4:  "version": "0.1.1",',
      'app/src-tauri/Cargo.toml:3:version = "0.1.1"',
      'app/src-tauri/Cargo.lock:11:version = "0.1.1"',
    ]);
    for (const s of SITES) expect(readVersions(after)[s]).toBe('0.1.1');
  });
  it('does not mutate its input', () => {
    const before = fixture();
    const copy = { ...before };
    setVersion(before, '0.2.0');
    expect(before).toEqual(copy);
  });
  it('keeps CRLF line endings and trailing newlines', () => {
    const before = fixture('\r\n');
    const after = setVersion(before, '0.1.1');
    for (const f of Object.keys(after)) {
      expect(after[f].replace(/\r\n/g, '')).not.toContain('\n');
      expect(after[f].endsWith('\r\n')).toBe(true);
    }
    expect(changedLines(before, after)).toHaveLength(6);
    expect(assertSameVersion(after)).toBe('0.1.1');
  });
  it('rejects a version that is not x.y.z', () => {
    expect(() => setVersion(fixture(), '0.1')).toThrow();
  });
  it('throws naming the site it cannot find', () => {
    const f = fixture();
    f['app/src-tauri/Cargo.lock'] = f['app/src-tauri/Cargo.lock'].replace(
      'name = "labnoteo-app"\n',
      'name = "other"\n',
    );
    expect(() => setVersion(f, '0.1.1')).toThrow(/Cargo\.lock#labnoteo-app/);
  });
});

describe('assertSameVersion', () => {
  it('returns the shared version', () => {
    expect(assertSameVersion(fixture())).toBe('0.1.0');
  });
  it('throws naming the one site that differs, listing every site', () => {
    const f = fixture();
    f['app/src-tauri/Cargo.lock'] = f['app/src-tauri/Cargo.lock'].replace(
      'name = "labnoteo-app"\nversion = "0.1.0"',
      'name = "labnoteo-app"\nversion = "0.0.9"',
    );
    let msg = '';
    try {
      assertSameVersion(f);
    } catch (e) {
      msg = (e as Error).message;
    }
    expect(msg).toContain('Cargo.lock#labnoteo-app = 0.0.9');
    for (const s of SITES) expect(msg).toContain(s);
  });
});

describe('CLI', () => {
  const script = join('app', 'scripts', 'releaseChain.mjs');
  it('`versions` on the real repo prints the one app version', () => {
    const r = spawnSync(process.execPath, [script, 'versions'], { cwd: repoRoot, encoding: 'utf8' });
    const pkg = JSON.parse(readFileSync(join(appDir, 'package.json'), 'utf8')) as { version: string };
    expect(r.stderr).toBe('');
    expect(r.status).toBe(0);
    expect(r.stdout.trim()).toBe(pkg.version);
    expect(pkg.version).toMatch(/^\d+\.\d+\.\d+$/);
  });
  it('an unknown command exits non-zero with usage', () => {
    const r = spawnSync(process.execPath, [script, 'nope'], { cwd: repoRoot, encoding: 'utf8' });
    expect(r.status).not.toBe(0);
    expect(r.stderr).toMatch(/usage/i);
  });
});
